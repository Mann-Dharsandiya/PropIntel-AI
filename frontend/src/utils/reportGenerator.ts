import jsPDF from "jspdf";

export interface FinancialReportData {
  emi: number;
  loanAmount: number;
  totalInterest: number;
  totalPayment: number;

  eligibleLoan: number;
  propertyBudget: number;

  roi: number;
  futureValue: number;

  affordability: number;

  buyCost: number;
  rentCost: number;
}

const money = (value: number) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(value);

export function generateFinancialReport(
  data: FinancialReportData
) {
  const pdf = new jsPDF();

  // =========================
  // HEADER
  // =========================

  pdf.setFillColor(30, 64, 175);
  pdf.rect(0, 0, 210, 28, "F");

  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(24);
  pdf.text("PropIntel AI", 15, 15);

  pdf.setFontSize(12);
  pdf.text(
    "Financial Intelligence Report",
    15,
    23
  );

  pdf.setTextColor(0, 0, 0);

  pdf.setFontSize(10);

  pdf.text(
    `Generated: ${new Date().toLocaleString()}`,
    15,
    36
  );

  // =========================
  // EMI
  // =========================

  pdf.setFontSize(16);
  pdf.text("EMI Summary", 15, 50);

  pdf.setFontSize(12);

  pdf.text(
    `Loan Amount : ${money(
      data.loanAmount
    )}`,
    20,
    62
  );

  pdf.text(
    `Monthly EMI : ${money(data.emi)}`,
    20,
    72
  );

  pdf.text(
    `Total Interest : ${money(
      data.totalInterest
    )}`,
    20,
    82
  );

  pdf.text(
    `Total Payment : ${money(
      data.totalPayment
    )}`,
    20,
    92
  );

  // =========================
  // Loan
  // =========================

  pdf.setFontSize(16);
  pdf.text(
    "Loan Eligibility",
    15,
    112
  );

  pdf.setFontSize(12);

  pdf.text(
    `Eligible Loan : ${money(
      data.eligibleLoan
    )}`,
    20,
    124
  );

  pdf.text(
    `Recommended Budget : ${money(
      data.propertyBudget
    )}`,
    20,
    134
  );

  // =========================
  // ROI
  // =========================

  pdf.setFontSize(16);
  pdf.text(
    "Investment Analysis",
    15,
    154
  );

  pdf.setFontSize(12);

  pdf.text(
    `ROI : ${data.roi.toFixed(
      2
    )}%`,
    20,
    166
  );

  pdf.text(
    `Future Value : ${money(
      data.futureValue
    )}`,
    20,
    176
  );

  // =========================
  // Buy vs Rent
  // =========================

  pdf.setFontSize(16);
  pdf.text(
    "Buy vs Rent",
    15,
    196
  );

  pdf.setFontSize(12);

  pdf.text(
    `Buying Cost : ${money(
      data.buyCost
    )}`,
    20,
    208
  );

  pdf.text(
    `Rent Cost : ${money(
      data.rentCost
    )}`,
    20,
    218
  );

  // =========================
  // Page 2
  // =========================

  pdf.addPage();

  pdf.setFontSize(18);

  pdf.text(
    "Affordability Analysis",
    15,
    20
  );

  pdf.setFontSize(13);

  pdf.text(
    `Affordability Score : ${data.affordability}/100`,
    20,
    36
  );

  let rating = "★☆☆☆☆";

  if (
    data.affordability >= 90 &&
    data.roi >= 20
  )
    rating = "★★★★★";
  else if (
    data.affordability >= 80
  )
    rating = "★★★★☆";
  else if (
    data.affordability >= 70
  )
    rating = "★★★☆☆";

  pdf.text(
    `Investment Rating : ${rating}`,
    20,
    50
  );

  pdf.setFontSize(16);

  pdf.text(
    "AI Financial Summary",
    15,
    75
  );

  pdf.setFontSize(12);

  pdf.text(
    "• Financial calculations generated by PropIntel AI.",
    20,
    90
  );

  pdf.text(
    "• Based on your inputs, the investment appears financially feasible.",
    20,
    102
  );

  pdf.text(
    "• Review market conditions before making a final decision.",
    20,
    114
  );

  pdf.text(
    "• This report is intended as a decision-support tool.",
    20,
    126
  );

  pdf.setDrawColor(180);

  pdf.line(15, 260, 195, 260);

  pdf.setFontSize(10);

  pdf.text(
    "Generated by PropIntel AI • Financial Intelligence Suite",
    15,
    270
  );

  pdf.save("PropIntel_Financial_Report.pdf");
}